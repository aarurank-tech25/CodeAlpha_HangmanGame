
import os
import re
import sqlite3
from pathlib import Path


BASE_DIR = Path(__file__).resolve().parent
SQLITE_DATABASE = BASE_DIR / "database" / "hangman.db"


def is_postgres():
    return bool(os.environ.get("DATABASE_URL", "").strip())


class PostgreSQLCursor:
    """Compatibility layer for existing SQLite-style SQL queries."""

    def __init__(self, cursor):
        self._cursor = cursor

    def _convert_sql(self, sql):
        statement = sql.strip()

        # PostgreSQL starts transactions automatically.
        # A SELECT ... FOR UPDATE will be added in multiplayer.py.
        if statement.upper().rstrip(";") == "BEGIN IMMEDIATE":
            return None

        # Convert SQLite auto-increment syntax to PostgreSQL identity.
        sql = re.sub(
            r"\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b",
            "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
            sql,
            flags=re.IGNORECASE
        )

        # Convert SQLite INSERT OR IGNORE.
        insert_ignore = re.match(
            r"^\s*INSERT\s+OR\s+IGNORE\s+INTO\b",
            sql,
            flags=re.IGNORECASE
        )

        if insert_ignore:
            sql = re.sub(
                r"INSERT\s+OR\s+IGNORE\s+INTO",
                "INSERT INTO",
                sql,
                count=1,
                flags=re.IGNORECASE
            )

            sql = sql.rstrip().rstrip(";")
            sql += " ON CONFLICT DO NOTHING"

        # PostgreSQL TEXT columns need an explicit cast
        # when CURRENT_TIMESTAMP is their default value.
        sql = re.sub(
            r"\b(TEXT\s+DEFAULT)\s+CURRENT_TIMESTAMP\b",
            r"\1 (CURRENT_TIMESTAMP::text)",
            sql,
            flags=re.IGNORECASE
        )

        # Convert SQLite placeholders to PostgreSQL placeholders.
        # Existing project queries use ? for parameters.
        sql = sql.replace("?", "%s")

        return sql

    def execute(self, sql, parameters=None):
        converted = self._convert_sql(sql)

        # BEGIN IMMEDIATE is not required for PostgreSQL.
        if converted is None:
            return self

        if parameters is None:
            self._cursor.execute(converted)
        else:
            self._cursor.execute(converted, parameters)

        return self

    def executemany(self, sql, parameters):
        converted = self._convert_sql(sql)

        if converted is None:
            return self

        self._cursor.executemany(converted, parameters)
        return self

    def fetchone(self):
        return self._cursor.fetchone()

    def fetchall(self):
        return self._cursor.fetchall()

    def fetchmany(self, size=None):
        if size is None:
            return self._cursor.fetchmany()
        return self._cursor.fetchmany(size)

    def __getattr__(self, name):
        return getattr(self._cursor, name)


class PostgreSQLConnection:
    """Connection wrapper that preserves the existing application API."""

    def __init__(self, connection):
        self._connection = connection

    def cursor(self, *args, **kwargs):
        return PostgreSQLCursor(
            self._connection.cursor(*args, **kwargs)
        )

    def commit(self):
        return self._connection.commit()

    def rollback(self):
        return self._connection.rollback()

    def close(self):
        return self._connection.close()

    def __getattr__(self, name):
        return getattr(self._connection, name)


def get_connection():
    database_url = os.environ.get("DATABASE_URL", "").strip()

    if database_url:
        try:
            import psycopg2
            from psycopg2.extras import DictCursor
        except ImportError as error:
            raise RuntimeError(
                "PostgreSQL driver missing. Install psycopg2-binary."
            ) from error

        # Some hosting platforms provide postgres:// URLs.
        if database_url.startswith("postgres://"):
            database_url = database_url.replace(
                "postgres://",
                "postgresql://",
                1
            )

        connection = psycopg2.connect(
            database_url,
            cursor_factory=DictCursor,
            connect_timeout=10
        )

        return PostgreSQLConnection(connection)

    # Local development continues using the existing SQLite database.
    SQLITE_DATABASE.parent.mkdir(
        parents=True,
        exist_ok=True
    )

    connection = sqlite3.connect(
        str(SQLITE_DATABASE),
        timeout=15
    )

    connection.row_factory = sqlite3.Row
    connection.execute("PRAGMA foreign_keys = ON")

    return connection


def initialize_database():
    conn = get_connection()
    cursor = conn.cursor()

    if is_postgres():
        id_definition = (
            "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
        )
    else:
        id_definition = "INTEGER PRIMARY KEY AUTOINCREMENT"

    try:
        # Player accounts
        cursor.execute(f"""
            CREATE TABLE IF NOT EXISTS players (
                id {id_definition},
                username TEXT UNIQUE NOT NULL,
                password TEXT NOT NULL,
                xp INTEGER DEFAULT 0,
                level INTEGER DEFAULT 1,
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
        """)

        # Normal game history
        cursor.execute(f"""
            CREATE TABLE IF NOT EXISTS game_history (
                id {id_definition},
                player_id INTEGER,
                word TEXT,
                score INTEGER,
                result TEXT,
                played_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                FOREIGN KEY(player_id) REFERENCES players(id)
            )
        """)

        # Player badges
        cursor.execute(f"""
            CREATE TABLE IF NOT EXISTS badges (
                id {id_definition},
                player_id INTEGER,
                badge_name TEXT,
                FOREIGN KEY(player_id) REFERENCES players(id)
            )
        """)

        # Daily challenge history
        cursor.execute(f"""
            CREATE TABLE IF NOT EXISTS daily_challenge_history (
                id {id_definition},
                player_id INTEGER NOT NULL,
                challenge_date TEXT NOT NULL,
                word TEXT NOT NULL,
                result TEXT NOT NULL,
                score INTEGER NOT NULL DEFAULT 0,
                UNIQUE(player_id, challenge_date)
            )
        """)

        # Multiplayer rooms
        cursor.execute(f"""
            CREATE TABLE IF NOT EXISTS multiplayer_rooms (
                id {id_definition},
                room_code TEXT UNIQUE NOT NULL,
                host_id INTEGER NOT NULL,
                guest_id INTEGER,
                word TEXT NOT NULL,
                guessed_letters TEXT DEFAULT '',
                wrong INTEGER DEFAULT 0,
                max_attempts INTEGER DEFAULT 6,
                status TEXT DEFAULT 'waiting',
                turn_player_id INTEGER,
                last_guess TEXT,
                last_guess_player_id INTEGER,
                last_guess_correct INTEGER,
                winner_id INTEGER,
                xp_reward INTEGER DEFAULT 150,
                created_at TEXT DEFAULT CURRENT_TIMESTAMP,
                updated_at TEXT DEFAULT CURRENT_TIMESTAMP
            )
        """)

        # Useful lookup indexes
        cursor.execute("""
            CREATE INDEX IF NOT EXISTS idx_game_history_player
            ON game_history(player_id)
        """)

        cursor.execute("""
            CREATE INDEX IF NOT EXISTS idx_badges_player
            ON badges(player_id)
        """)

        cursor.execute("""
            CREATE INDEX IF NOT EXISTS idx_multiplayer_room_code
            ON multiplayer_rooms(room_code)
        """)

        conn.commit()

        print(
            "PostgreSQL database initialized successfully!"
            if is_postgres()
            else "SQLite database initialized successfully!"
        )

    except Exception:
        conn.rollback()
        raise

    finally:
        conn.close()


# Use the correct database integrity exception in application code.
if is_postgres():
    try:
        import psycopg2
        IntegrityError = psycopg2.IntegrityError
    except ImportError:
        IntegrityError = sqlite3.IntegrityError
else:
    IntegrityError = sqlite3.IntegrityError


if __name__ == "__main__":
    initialize_database()
